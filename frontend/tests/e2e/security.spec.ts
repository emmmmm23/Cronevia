test('an expired drafting session can finish 2FA without losing the draft',async({page})=>{
 await securityFixture(page,true)
 await page.goto('/verify-2fa')
 await page.getByLabel('Authenticator code',{exact:true}).fill('123456')
 await page.getByRole('button',{name:'Verify and continue'}).click()
 await expect(page).toHaveURL(/127\.0\.0\.1:5177\/$/)
 await page.goto('/trips/new')
 await page.getByLabel('Trip name',{exact:true}).fill('Keep my private draft')
 const expired=(r:any)=>r.fulfill({status:401,contentType:'application/json',body:JSON.stringify({code:'bad_jwt',message:'JWT expired'})})
 await page.route('**/auth/v1/user',expired)
 await page.getByRole('button',{name:'Create trip',exact:true}).click()
 const login=page.getByRole('group',{name:'Sign in again'})
 await expect(login).toBeVisible()
 await page.unroute('**/auth/v1/user',expired)
 await login.getByLabel('Email address',{exact:true}).fill('planner@example.test')
 await login.getByLabel('Password',{exact:true}).fill('fixture-current-password')
 await login.getByRole('button',{name:'Sign in',exact:true}).click()
 await expect(login.getByLabel('Authenticator code',{exact:true})).toBeVisible()
 await expect(page.getByLabel('Trip name',{exact:true})).toHaveValue('Keep my private draft')
 await login.getByLabel('Authenticator code',{exact:true}).fill('123456')
 await login.getByRole('button',{name:'Verify and restore session'}).click()
 await expect(login).not.toBeVisible()
 await expect(page.getByLabel('Trip name',{exact:true})).toHaveValue('Keep my private draft')
 await page.getByRole('button',{name:'Create trip',exact:true}).click()
 await expect(page.getByRole('button',{name:'Add your first place',exact:true})).toBeVisible()
})
