import assert from 'node:assert/strict'
import {readFile} from 'node:fs/promises'
export async function testAccountSecurity(db,asUser,alice,bob,admin){
 await db.exec('RESET ROLE')
 // The upgrade is idempotent on the existing schema.
 const migration=await readFile(new URL('../../supabase/migrations/20261028000004_account_security.sql',import.meta.url),'utf8')
 await db.exec(migration)
 const active=async()=> (await db.query('SELECT is_account_active() AS ok')).rows[0].ok
 await asUser(alice)
 assert.equal(await active(),true)
 assert.equal((await db.query('SELECT consume_place_request() AS ok')).rows[0].ok,true)
 assert.equal((await db.query('SELECT consume_place_request() AS ok')).rows[0].ok,false)
 await assert.rejects(()=>db.query('SELECT * FROM cronevia_private.place_quotas'))
 await db.exec('RESET ROLE')
 await db.query("INSERT INTO auth.mfa_factors(user_id,status) VALUES($1,'unverified')",[alice])
 await asUser(alice);assert.equal(await active(),true)
 await db.exec('RESET ROLE')
 await db.query("UPDATE auth.mfa_factors SET status='verified' WHERE user_id=$1",[alice])
 await asUser(alice)
 // Missing/old claims must fail closed, including security-definer write/read RPCs.
 for(const claims of ['{}','{"aal":"aal1"}']){
  await db.query("SELECT set_config('request.jwt.claims',$1,false)",[claims])
  assert.equal(await active(),false)
  for(const table of ['profiles','trips','journal_entries','memories','creative_trackers','tracker_logs','tracker_boards'])
   assert.equal((await db.query('SELECT * FROM '+table)).rows.length,0)
  await assert.rejects(()=>db.query('SELECT list_capsules()'))
  await assert.rejects(()=>db.query('SELECT consume_place_request()'))
  await assert.rejects(()=>db.query("SELECT create_capsule('Blocked','Hidden',current_date+1)"))
  await assert.rejects(()=>db.query("INSERT INTO storage.objects(bucket_id,name) VALUES('cronevia-media',$1)",[alice+'/blocked.png']))
 }
 await db.query("SELECT set_config('request.jwt.claims','{\"aal\":\"aal2\"}',false)")
 assert.equal(await active(),true)
 assert.ok((await db.query('SELECT * FROM profiles')).rows.some(p=>p.user_id===alice))
 assert.equal((await db.query('SELECT * FROM profiles WHERE user_id=$1',[bob])).rows.length,0)
 await db.query("INSERT INTO storage.objects(bucket_id,name) VALUES('cronevia-media',$1)",[alice+'/verified.png'])
 await db.exec('RESET ROLE')
 await db.query("UPDATE cronevia_private.place_quotas SET used=30,last_request=clock_timestamp()-interval '2 seconds' WHERE user_id=$1",[alice])
 await asUser(alice);assert.equal((await db.query('SELECT consume_place_request() AS ok')).rows[0].ok,false)
 await db.exec('RESET ROLE')
 await db.query("UPDATE cronevia_private.place_quotas SET window_start=clock_timestamp()-interval '2 minutes' WHERE user_id=$1",[alice])
 await asUser(alice);assert.equal((await db.query('SELECT consume_place_request() AS ok')).rows[0].ok,true)
 await db.exec('RESET ROLE')
 await db.query("INSERT INTO auth.mfa_factors(user_id,status) VALUES($1,'verified')",[admin])
 await asUser(admin)
 await db.query("SELECT set_config('request.jwt.claims','{\"aal\":\"aal1\"}',false)")
 assert.equal((await db.query('SELECT is_super_admin() AS ok')).rows[0].ok,false)
 await assert.rejects(()=>db.query('SELECT * FROM get_user_statistics()'))
 await db.query("SELECT set_config('request.jwt.claims','{\"aal\":\"aal2\"}',false)")
 assert.equal((await db.query('SELECT is_super_admin() AS ok')).rows[0].ok,true)
 await db.exec('RESET ROLE')
 await db.query("DELETE FROM auth.mfa_factors WHERE user_id=$1",[alice])
 await asUser(alice)
 await db.query("SELECT set_config('request.jwt.claims','{\"aal\":\"aal1\"}',false)")
 assert.equal(await active(),true)
 await db.exec('RESET ROLE; SET ROLE anon')
 await assert.rejects(()=>db.query('SELECT is_mfa_satisfied()'))
 await assert.rejects(()=>db.query('SELECT consume_place_request()'))
 assert.equal((await db.query('SELECT security_schema_version() AS version')).rows[0].version,'20261028.4')
 console.log('PASS: MFA gates direct reads, writes, storage and definer RPCs; old/missing claims fail closed; admin MFA, factor removal, quota denial/reset and anonymous isolation.')
}
