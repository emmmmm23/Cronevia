import {test,expect,type Page} from '@playwright/test'
import {fixture,noOverflow,owner} from './planner-fixture'
import {mkdir} from 'node:fs/promises'
async function securityFixture(page:Page,enabled=false){
 const core=await fixture(page)
 // All requests are intercepted locally. No hosted account or real OTP is used.
 const factors:any[]=enabled?[{id:'factor-one',factor_type:'totp',status:'verified',friendly_name:'My authenticator',created_at:new Date().toISOString()}]:[]
 let prefs:any={user_id:owner,theme:'vintage',timezone:'Asia/Manila',email_notifications:true}
 const calls={profile:0,password:0,unenroll:0,enroll:0,signouts:[] as string[]}
 const json=(route:any,value:any,status=200)=>route.fulfill({status,contentType:'application/json',body:JSON.stringify(value)})
 const user=()=>({...core.user,factors})
 function session(aal='aal1',recovery=false){
  const payload={sub:owner,exp:Math.floor(Date.now()/1000)+3600,role:'authenticated',aud:'authenticated',aal,amr:[{method:recovery?'recovery':'password',timestamp:Math.floor(Date.now()/1000)}]}
  return {...core.session,user:user(),access_token:Buffer.from('{"alg":"HS256"}').toString('base64url')+'.'+Buffer.from(JSON.stringify(payload)).toString('base64url')+'.fixture'}
 }
 await page.route('**/auth/v1/user',route=>{
  if(route.request().method()==='PUT'){calls.password++;const body=route.request().postDataJSON();const token=route.request().headers().authorization?.split(' ')[1];const recovery=token&&JSON.parse(Buffer.from(token.split('.')[1],'base64url').toString()).amr?.some((a:any)=>a.method==='recovery');if(body.password&&!recovery&&(!body.current_password||body.current_password!=='fixture-current-password'))return json(route,{code:'reauthentication_needed',message:'private diagnostic must not reach UI'},400)}
  return json(route,user())
 })
 await page.route('**/auth/v1/token?**',route=>{
  if(route.request().postDataJSON().password==='wrong-password')return json(route,{code:'invalid_credentials',message:'private auth detail'},400)
  return json(route,session())
 })
 await page.route('**/auth/v1/logout?**',route=>{calls.signouts.push(new URL(route.request().url()).searchParams.get('scope')||'global');return route.fulfill({status:204})})
 await page.route('**/auth/v1/factors',route=>{
  calls.enroll++;const f={id:'factor-'+calls.enroll,factor_type:'totp',status:'unverified',friendly_name:route.request().postDataJSON().friendly_name,created_at:new Date().toISOString()};factors.push(f)
  return json(route,{...f,totp:{qr_code:'<svg xmlns="http://www.w3.org/2000/svg" width="180" height="180"><rect width="180" height="180" fill="white"/><path d="M20 20h40v40H20z M120 20h40v40h-40z M20 120h40v40H20z" fill="black"/></svg>',secret:'FIXTURESETUPKEYONLY',uri:'otpauth://totp/fixture'}})
 })
 await page.route('**/auth/v1/factors/*/challenge',route=>json(route,{id:'challenge-fixture',type:'totp',expires_at:Math.floor(Date.now()/1000)+60}))
 await page.route('**/auth/v1/factors/*/verify',route=>{
  const data=route.request().postDataJSON()
  if(data.code!=='123456')return json(route,{code:data.code==='999999'?'mfa_challenge_expired':'mfa_verification_failed',message:'private verification diagnostic'},400)
  const id=new URL(route.request().url()).pathname.split('/').at(-2),factor=factors.find(f=>f.id===id)
  if(factor)factor.status='verified'
  return json(route,session('aal2'))
 })
 await page.route('**/auth/v1/factors/*',route=>{
  if(route.request().method()!=='DELETE')return route.fallback()
  calls.unenroll++;const id=new URL(route.request().url()).pathname.split('/').at(-1);const index=factors.findIndex(f=>f.id===id);if(index>=0)factors.splice(index,1)
  return json(route,{id})
 })
 await page.route('**/rest/v1/profiles?**',route=>{calls.profile++;return json(route,{...core.user,user_id:owner,full_name:'Local security reviewer',username:'fixture',role:'user',account_status:'active',timezone:'Asia/Manila'})})
 await page.route('**/rest/v1/user_settings?**',route=>{if(route.request().method()==='POST'||route.request().method()==='PATCH')prefs={...prefs,...route.request().postDataJSON()};return json(route,prefs)})
 return {calls,factors,prefs:()=>prefs,session,user,core}
}
