test('2FA enrollment stays pending until verified, gates new sessions and verifies removal',async({page})=>{
 const f=await securityFixture(page)
 await page.goto('/settings')
 const card=page.getByRole('region',{name:'Two-factor authentication'})
 await card.getByRole('button',{name:'Set up two-factor authentication',exact:true}).click()
 await expect(card.locator('.authenticator-qr')).toBeVisible()
 await expect(card.locator('.factor-status')).toHaveText('Off')
 await card.getByLabel('Authenticator code',{exact:true}).fill('000000')
 await card.getByRole('button',{name:'Verify and enable 2FA'}).click()
 await expect(card.getByRole('alert')).toContainText('latest code')
 expect(f.factors[0].status).toBe('unverified')
 await card.getByLabel('Authenticator code',{exact:true}).fill('123456')
 await card.getByRole('button',{name:'Verify and enable 2FA'}).click()
 await expect(card.locator('.factor-status')).toHaveText('On')
 await expect(card.locator('.authenticator-qr')).toHaveCount(0)
 expect(await page.evaluate(()=>JSON.stringify(localStorage))).not.toContain('FIXTURESETUPKEYONLY')
 // A new password-only session cannot fetch private profile/content before 2FA.
 await page.evaluate(session=>{const key=Object.keys(localStorage).find(k=>k.endsWith('-auth-token'))!;localStorage.setItem(key,JSON.stringify(session))},f.session())
 const before=f.calls.profile
 await page.goto('/trips')
 await expect(page).toHaveURL(/verify-2fa/)
 expect(f.calls.profile).toBe(before)
 await page.getByLabel('Authenticator code',{exact:true}).fill('999999')
 await page.getByRole('button',{name:'Verify and continue'}).click()
 await expect(page.getByRole('alert')).toContainText('latest code')
 await page.getByLabel('Authenticator code',{exact:true}).fill('123456')
 await page.getByRole('button',{name:'Verify and continue'}).click()
 await expect(page).toHaveURL(/\/trips$/)
 await page.goto('/settings')
 await card.getByRole('button',{name:'Remove authenticator',exact:true}).click()
 await card.getByLabel('Code from the authenticator being removed').fill('000000')
 await card.getByRole('button',{name:'Verify and remove'}).click()
 expect(f.calls.unenroll).toBe(0)
 await card.getByLabel('Code from the authenticator being removed').fill('123456')
 await card.getByRole('button',{name:'Verify and remove'}).click()
 await expect(card.locator('.factor-status')).toHaveText('Off')
 expect(f.calls.unenroll).toBe(1)
})
